const F = require('./calc.js'), assert = require('assert');
let c = F.parseCidr('192.168.10.77/27'), r = F.info(c.ip, c.prefix);
assert.strictEqual(r.network, '192.168.10.64'); assert.strictEqual(r.broadcast, '192.168.10.95');
assert.strictEqual(r.first, '192.168.10.65'); assert.strictEqual(r.last, '192.168.10.94');
assert.strictEqual(r.usable, 30); assert.strictEqual(r.mask, '255.255.255.224'); assert.strictEqual(r.wildcard, '0.0.0.31');
assert.ok(r.private); assert.ok(r.cls.startsWith('C'));
r = F.info(F.ipToInt('10.20.30.40'), 8);
assert.strictEqual(r.broadcast, '10.255.255.255'); assert.strictEqual(r.usable, 16777214);
r = F.info(F.ipToInt('200.1.1.1'), 32); assert.strictEqual(r.usable, 1);
r = F.info(F.ipToInt('200.1.1.1'), 0); assert.strictEqual(r.mask, '0.0.0.0'); assert.strictEqual(r.broadcast, '255.255.255.255');
let s = F.split(F.ipToInt('172.16.0.0'), 16, 6);
assert.strictEqual(s.borrow, 3); assert.strictEqual(s.newPrefix, 19); assert.strictEqual(s.total, 8);
assert.strictEqual(s.list[1].network, '172.16.32.0'); assert.strictEqual(s.list[7].broadcast, '172.16.255.255');
assert.strictEqual(s.list[0].usable, 8190);
let v = F.vlsm(F.ipToInt('192.168.1.0'), 24, [25, 100, 50]);
assert.deepStrictEqual(v.list.map(x => x.network + '/' + x.prefix), ['192.168.1.0/25', '192.168.1.128/26', '192.168.1.192/27']);
assert.strictEqual(v.free, 32);
assert.throws(() => F.vlsm(F.ipToInt('192.168.1.0'), 24, [200, 100]));
assert.throws(() => F.parseCidr('192.168.1.300/24'));
assert.strictEqual(F.vlsm(F.ipToInt('192.168.1.0'), 24, [2]).list[0].prefix, 30);
console.log('All checks passed');
